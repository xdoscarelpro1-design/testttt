	static const int KnownOffsetsCount = sizeof(KnownOffsets) / sizeof(KnownOffsets[0]);

	// Find exact offsets for a build number
	inline const VersionOffsets* FindOffsets(int buildNumber)
	{
		for (int i = 0; i < KnownOffsetsCount; i++)
		{
			if (KnownOffsets[i].buildNumber == buildNumber)
				return &KnownOffsets[i];
		}
		return nullptr;
	}

	// Find closest known build (fallback for unknown versions)
	inline const VersionOffsets* FindClosestOffsets(int buildNumber)
	{
		const VersionOffsets* closest = nullptr;
		int minDiff = INT_MAX;
		for (int i = 0; i < KnownOffsetsCount; i++)
		{
			int diff = abs(KnownOffsets[i].buildNumber - buildNumber);
			if (diff < minDiff)
			{
				minDiff = diff;
				closest = &KnownOffsets[i];
			}
		}
		return closest;
	}
